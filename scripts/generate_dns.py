"""Portable Mihomo DNS settings; no subscription or device-specific data."""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
WIRE = '?dns=BNIBAAABAAAAAAAAB2V4YW1wbGUDY29tAAABAAE'
RESOLVERS = [('CF', 'https://cloudflare-dns.com/dns-query'),
             ('Google', 'https://dns.google/dns-query')]
DOMESTIC = ['https://223.5.5.5/dns-query#DIRECT',
            'https://223.6.6.6/dns-query#DIRECT']
SERVICE_DNS = {'netflix': '🎥 Netflix', 'hbo': '🎬 HBO', 'tiktok': '👯‍♂️ TikTok'}
TAIWAN = '(?i)(TW|台湾|台灣|Taiwan|台北|新北|桃园|桃園|彰化|🇹🇼)'


def dns_config():
    upstream = [url + '#DNS-' + name + '-Auto' for name, url in RESOLVERS]
    # Keep domestic answers for clients/OpenClash filters requesting real IPs.
    policy = {'geosite:cn': DOMESTIC.copy()}
    policy.update({'geosite:' + service: [url + '#' + group for _, url in RESOLVERS]
                   for service, group in SERVICE_DNS.items()})
    return {'enable': True, 'listen': '127.0.0.1:1053', 'ipv6': False,
            'enhanced-mode': 'fake-ip', 'fake-ip-range': '198.18.0.1/16',
            'fake-ip-filter': ['*.lan', '*.local', '*.home.arpa', 'localhost'],
            'respect-rules': False,
            'default-nameserver': [x.split('#')[0] for x in DOMESTIC],
            'proxy-server-nameserver': DOMESTIC.copy(),
            # DIRECT resolves locally even if a service policy uses proxy DNS.
            # respect-rules routes DNS connections; it does not select these.
            'direct-nameserver': DOMESTIC.copy(),
            'direct-nameserver-follow-policy': False,
            'nameserver': upstream, 'nameserver-policy': policy}


def group_lines():
    rows = ['', '; DNS only: check actual DoH URLs; Taiwan first, US backup.']
    for name, url in RESOLVERS:
        prefix = 'DNS-' + name
        rows.append('custom_proxy_group=' + prefix + '-TW`fallback`' + TAIWAN
                    + '`[]REJECT`' + url + WIRE + '`300,4')
        rows.append('custom_proxy_group=' + prefix + '-Auto`fallback`[]'
                    + prefix + '-TW`[]美国节点`' + url + WIRE + '`300,4')
    return rows


def build_base():
    config = {'mode': 'rule', 'log-level': 'info', 'dns': dns_config(),
              'sniffer': {'enable': True, 'parse-pure-ip': True,
                          'force-dns-mapping': True, 'override-destination': False,
                          'sniff': {'TLS': {'ports': [443, 8443]},
                                    'HTTP': {'ports': [80, 8080]}}},
              'proxies': [], 'proxy-groups': [], 'rules': []}
    text = '# Generated by scripts/generate_dns.py; requires Mihomo.\n'
    text += yaml.safe_dump(config, allow_unicode=True, sort_keys=False)
    (ROOT / 'config/clash-base.yaml').write_text(text)

